/**
 * SVG Exporter - Generates plotter-ready SVG files
 * Optimized for iDraw H SE A3 pen plotter
 * 
 * Features:
 * - Color-grouped layers for easy pen changes
 * - Polyline output for efficient plotting
 * - 3 decimal precision for manageable file sizes
 * - A3 dimensions with mm units
 */

import { paperWidth, paperHeight, paperFormat } from './weaver.js';

// Precision for coordinate values (decimal places)
const PRECISION = 3;

/**
 * Format a number to specified precision
 * @param {number} num - Number to format
 * @returns {string} Formatted number string
 */
function formatNum(num) {
    return num.toFixed(PRECISION);
}

/**
 * Convert points array to SVG polyline points string
 * @param {Array<{x: number, y: number}>} points - Array of point objects
 * @returns {string} SVG-compatible points string
 */
function pointsToString(points) {
    return points
        .map(p => `${formatNum(p.x)},${formatNum(p.y)}`)
        .join(' ');
}

/**
 * Get a readable color name from hex value
 * @param {string} hex - Hex color value
 * @returns {string} Color name or simplified hex
 */
function getColorName(hex) {
    const colorNames = {
        '#00bcd4': 'cyan',
        '#e91e63': 'magenta',
        '#ffc107': 'yellow',
        '#212121': 'black',
        '#4caf50': 'green',
        '#ff9800': 'orange',
        '#9c27b0': 'purple',
        '#2196f3': 'blue',
        '#f44336': 'red'
    };
    
    const lower = hex.toLowerCase();
    return colorNames[lower] || hex.replace('#', '');
}

/**
 * Group threads by their assigned pen/color
 * @param {Object} threads - Weave object with warp and weft arrays
 * @param {Object} config - Configuration with pen assignments
 * @returns {Map} Map of color -> threads array
 */
function groupThreadsByColor(threads, config) {
    const groups = new Map();
    
    // Get pen colors
    const warpColor = config.pens[config.warpPen];
    const weftColor = config.pens[config.weftPen];
    
    // Initialize groups
    if (!groups.has(warpColor)) {
        groups.set(warpColor, []);
    }
    if (!groups.has(weftColor)) {
        groups.set(weftColor, []);
    }
    
    // Add warp threads
    threads.warp.forEach(thread => {
        groups.get(warpColor).push(thread);
    });
    
    // Add weft threads
    threads.weft.forEach(thread => {
        groups.get(weftColor).push(thread);
    });
    
    return groups;
}

/**
 * Generate SVG layer group for a set of threads
 * @param {string} color - Hex color for this layer
 * @param {Array} threads - Array of thread objects
 * @param {number} strokeWidth - Stroke width in mm
 * @param {number} layerIndex - Layer index for ID
 * @returns {string} SVG group element string
 */
function generateLayer(color, threads, strokeWidth, layerIndex) {
    const colorName = getColorName(color);
    const layerId = `layer-pen-${layerIndex + 1}-${colorName}`;
    
    const polylines = threads.map(thread => {
        const pointsStr = pointsToString(thread.points);
        return `    <polyline points="${pointsStr}" />`;
    }).join('\n');
    
    return `  <g id="${layerId}" stroke="${color}" fill="none" stroke-width="${formatNum(strokeWidth)}" stroke-linecap="round" stroke-linejoin="round">
${polylines}
  </g>`;
}

/**
 * Export weave pattern as SVG string
 * Optimized for pen plotter with color-grouped layers
 * 
 * @param {Object} threads - Weave object with warp and weft arrays
 * @param {Object} config - Export configuration
 * @param {Array<string>} config.pens - Array of pen colors (hex)
 * @param {number} config.warpPen - Index of pen for warp threads
 * @param {number} config.weftPen - Index of pen for weft threads
 * @param {number} config.strokeWidth - Stroke width in mm (default 0.3)
 * @returns {string} Complete SVG string
 */
export function exportSVG(threads, config) {
    const {
        pens = ['#00bcd4', '#e91e63', '#ffc107', '#212121'],
        warpPen = 0,
        weftPen = 1,
        strokeWidth = 0.3
    } = config;

    // Group threads by color
    const colorGroups = groupThreadsByColor(threads, { pens, warpPen, weftPen });
    
    // Generate layers for each color
    const layers = [];
    let layerIndex = 0;
    
    colorGroups.forEach((groupThreads, color) => {
        if (groupThreads.length > 0) {
            layers.push(generateLayer(color, groupThreads, strokeWidth, layerIndex));
            layerIndex++;
        }
    });
    
    // Assemble complete SVG
    const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg"
     width="${paperWidth}mm"
     height="${paperHeight}mm"
     viewBox="0 0 ${paperWidth} ${paperHeight}">
  <!-- Generated by The Digital Loom -->
  <!-- Dimensions: ${paperWidth}mm x ${paperHeight}mm (${paperFormat}) -->

${layers.join('\n\n')}
</svg>`;

    return svg;
}

/**
 * Export SVG with separate files per color layer
 * Useful when plotter software doesn't support layer selection
 * 
 * @param {Object} threads - Weave object with warp and weft arrays
 * @param {Object} config - Export configuration
 * @returns {Array<{filename: string, content: string, color: string}>} Array of file objects
 */
export function exportSVGByLayers(threads, config) {
    const {
        pens = ['#00bcd4', '#e91e63', '#ffc107', '#212121'],
        warpPen = 0,
        weftPen = 1,
        strokeWidth = 0.3
    } = config;

    const colorGroups = groupThreadsByColor(threads, { pens, warpPen, weftPen });
    const files = [];
    let layerIndex = 0;

    colorGroups.forEach((groupThreads, color) => {
        if (groupThreads.length > 0) {
            const colorName = getColorName(color);
            const layer = generateLayer(color, groupThreads, strokeWidth, layerIndex);
            
            const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg"
     width="${paperWidth}mm"
     height="${paperHeight}mm"
     viewBox="0 0 ${paperWidth} ${paperHeight}">
  <!-- Layer ${layerIndex + 1}: ${colorName} (${paperFormat}) -->

${layer}
</svg>`;

            files.push({
                filename: `weave-layer-${paperFormat}-${layerIndex + 1}-${colorName}.svg`,
                content: svg,
                color: color
            });
            
            layerIndex++;
        }
    });

    return files;
}

/**
 * Calculate estimated file size of SVG string
 * @param {string} svgString - SVG content
 * @returns {Object} Size information
 */
export function getSVGStats(svgString) {
    const bytes = new Blob([svgString]).size;
    const kb = bytes / 1024;
    const mb = kb / 1024;
    
    // Count elements
    const polylineCount = (svgString.match(/<polyline/g) || []).length;
    const groupCount = (svgString.match(/<g id=/g) || []).length;
    
    return {
        bytes,
        kilobytes: kb.toFixed(2),
        megabytes: mb.toFixed(3),
        polylineCount,
        layerCount: groupCount,
        readable: kb < 1024 ? `${kb.toFixed(1)} KB` : `${mb.toFixed(2)} MB`
    };
}

/**
 * Trigger download of SVG file in browser
 * @param {string} svgString - SVG content
 * @param {string} filename - Filename for download
 */
export function downloadSVG(svgString, filename = 'weave-pattern.svg') {
    const blob = new Blob([svgString], { type: 'image/svg+xml' });
    const url = URL.createObjectURL(blob);
    
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    
    // Clean up
    setTimeout(() => URL.revokeObjectURL(url), 100);
}

/**
 * Generate timestamp-based filename
 * @returns {string} Filename with timestamp
 */
export function generateFilename() {
    const now = new Date();
    const timestamp = now.toISOString()
        .replace(/[:.]/g, '-')
        .slice(0, 19);
    return `digital-loom-${paperFormat}-${timestamp}.svg`;
}
